"""Build play/checklist-data.js from the content_*.py files.
Run from the repo root:  python3 tools/checklist/build.py
Checks: unique codes, every fig file exists, no stray control characters (a sign of a non-raw string eating a backslash),
balanced $...$ math, and no plain hyphen-minus used as a math minus outside TeX."""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from content_cpas import CPAS
from content_bbfl import BBFL
from content_ochem_lab import OCHEM, LAB

PHYS = {"CPAS-01", "CPAS-02", "CPAS-03", "CPAS-04", "CPAS-12", "CPAS-13", "CPAS-05", "CPAS-11"}
SECTIONS = [("PHYS", "Physics"), ("CHEM", "General Chemistry"), ("BIO", "Biology & Biochem"), ("ORG", "Organic Chemistry"), ("LAB", "Lab Techniques")]

def cat(code):
    if code.startswith("CPAS"): return "PHYS" if code in PHYS else "CHEM"
    return {"BBFL": "BIO", "OChe": "ORG", "Lab-": "LAB"}[code[:4]]

def unq(x):
    """Raw strings keep the backslash in \\" ; turn it back into a plain quote."""
    if isinstance(x, str): return x.replace('\\"', '"')
    if isinstance(x, (list, tuple)): return type(x)(unq(y) for y in x)
    if isinstance(x, dict): return {k: unq(v) for k, v in x.items()}
    return x

errs = []
def walk(x, where):
    if isinstance(x, str):
        if re.search(r"[\x00-\x08\x0b-\x1f]", x): errs.append(f"{where}: control character (use a raw string): {x[:60]!r}")
        if x.count("$") % 2: errs.append(f"{where}: unbalanced $ in {x[:60]!r}")
    elif isinstance(x, (list, tuple)):
        for i, y in enumerate(x): walk(y, f"{where}[{i}]")
    elif isinstance(x, dict):
        for k, y in x.items(): walk(y, f"{where}.{k}")

cards = []
for c in map(unq, CPAS + BBFL + OCHEM + LAB):
    walk(c, c["code"])
    if c.get("fig") and not os.path.exists(os.path.join(ROOT, "play/fig/chk", c["fig"])): errs.append(f"{c['code']}: missing figure {c['fig']}")
    pts = [p if isinstance(p, str) else {"t": p[0], "sub": p[1]} for p in c["points"]]
    cards.append(dict(code=c["code"], cat=cat(c["code"]), title=c["title"], hook=c["hook"],
                      formulas=[{"tex": f, "say": s} for f, s in c["formulas"]],
                      vars=[{"tex": a, "name": b, "unit": u, "eli5": e} for a, b, u, e in c["vars"]],
                      eli5=c["eli5"], points=pts, traps=c["traps"], mnemonics=c["mnemonics"],
                      fig=c.get("fig"), figcap=c.get("figcap", "")))
codes = [c["code"] for c in cards]
dups = {x for x in codes if codes.count(x) > 1}
if dups: errs.append(f"duplicate codes {dups}")
order = [k for k, _ in SECTIONS]
cards.sort(key=lambda c: order.index(c["cat"]))  # stable: keeps teaching order within a section
if errs:
    print("\n".join(errs)); sys.exit(1)
out = os.path.join(ROOT, "play/checklist-data.js")
with open(out, "w") as f:
    f.write("// Generated by tools/checklist/build.py from tools/checklist/content_*.py. Edit those, not this file.\n")
    f.write("window.CHECKLIST = " + json.dumps({"sections": [{"key": k, "label": l} for k, l in SECTIONS], "cards": cards}, ensure_ascii=False, indent=0) + ";\n")
print(f"wrote {out}: {len(cards)} cards, {sum(1 for c in cards if c['fig'])} figures")
